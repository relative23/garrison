//! The polkit rule that lets the broker user manage only its units.
//!
//! The operating system enforces the allowlist: even a compromised broker
//! process can start or restart only the configured unit/verb pairs, and
//! nothing else.

use std::collections::BTreeMap;

use garrison_core::config::Action;

const HEADER: &str = "// Generated by `garrison broker polkit-rule`; do not edit by hand.
// Regenerate after changing [[actions]] in garrison.toml.
";

/// A JSON string; unit and user names are ASCII, so the escaping is plain.
fn quoted(text: &str) -> String {
    serde_json::Value::from(text).to_string()
}

/// The rule that lets `user` run exactly the configured unit operations.
pub fn rule(actions: &[Action], user: &str) -> String {
    let mut allowed: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for action in actions {
        let verbs = allowed.entry(action.unit.as_str()).or_default();
        let verb = action.operation.as_str();
        if !verbs.contains(&verb) {
            verbs.push(verb);
        }
    }
    // One line of JSON: ", " between items and ": " after keys.
    let entries: Vec<String> = allowed
        .iter()
        .map(|(unit, verbs)| {
            let verbs: Vec<String> = verbs.iter().map(|verb| quoted(verb)).collect();
            format!("{}: [{}]", quoted(unit), verbs.join(", "))
        })
        .collect();
    let allowed = format!("{{{}}}", entries.join(", "));
    let user = quoted(user);
    // ES5 syntax: polkit's embedded JavaScript engine is not a full modern runtime.
    format!(
        "{HEADER}polkit.addRule(function (action, subject) {{
    if (action.id !== \"org.freedesktop.systemd1.manage-units\" ||
        subject.user !== {user}) {{
        return polkit.Result.NOT_HANDLED;
    }}
    var allowed = {allowed};
    var unit = action.lookup(\"unit\");
    var verb = action.lookup(\"verb\");
    if (Object.prototype.hasOwnProperty.call(allowed, unit) &&
        allowed[unit].indexOf(verb) !== -1) {{
        return polkit.Result.YES;
    }}
    return polkit.Result.NOT_HANDLED;
}});
"
    )
}

#[cfg(test)]
mod tests {
    use garrison_core::config::Operation;

    use super::*;

    fn action(unit: &str, operation: Operation) -> Action {
        Action {
            id: "a".into(),
            title: "A".into(),
            description: "d".into(),
            confirmation: "A".into(),
            unit: unit.into(),
            operation,
            cooldown_seconds: 0,
            timeout_seconds: 60,
            operator: false,
        }
    }

    #[test]
    fn the_rule_lists_each_unit_once_with_its_verbs() {
        let actions = [
            action("z.service", Operation::Start),
            action("a.service", Operation::Restart),
            action("a.service", Operation::Start),
            action("a.service", Operation::Restart),
        ];
        let text = rule(&actions, "garrison-broker");
        assert!(text.starts_with(HEADER));
        assert!(text.contains(
            "var allowed = {\"a.service\": [\"restart\", \"start\"], \"z.service\": [\"start\"]};\n"
        ));
        assert!(text.contains("subject.user !== \"garrison-broker\") {\n"));
        assert!(text.ends_with("    return polkit.Result.NOT_HANDLED;\n});\n"));
        assert_eq!(text, include_str!("../tests/fixtures/polkit.rules"));
    }
}
